import { useCallback, useEffect, useState } from "react";
import { AccountProvider } from "./AccountContext";
import { AccountMenu } from "./components/AccountMenu";
import { ErrorBoundary } from "./components/ErrorBoundary";
import { ComparisonPage } from "./pages/ComparisonPage";
import { DashboardPage } from "./pages/DashboardPage";
import { FedTrackerPage } from "./pages/FedTrackerPage";
import { JournalPage } from "./pages/JournalPage";
import { useAccount } from "./useAccount";
import { useTheme } from "./useTheme";
import { ThemePicker } from "./components/ThemePicker";
import "./design.css";

type Tab = "dashboard" | "comparison" | "journal" | "fed";

const TABS: { id: Tab; label: string }[] = [
  { id: "dashboard", label: "Dashboard" },
  { id: "comparison", label: "Compare" },
  { id: "journal", label: "Journal" },
  { id: "fed", label: "Fed Tracker" },
];

const TAB_STORAGE_KEY = "vantage.tab";


/**
 * The token from an emailed sign-in link.
 *
 * The link points at the app rather than the API so the cookie is set from a
 * normal page visit. It is stripped from the address bar once read, so a
 * shared or bookmarked URL never carries a live token.
 */
function readSignInToken(): string | null {
  try {
    return new URLSearchParams(window.location.search).get("token");
  } catch {
    return null;
  }
}

function clearSignInToken() {
  try {
    const url = new URL(window.location.href);
    url.searchParams.delete("token");
    window.history.replaceState({}, "", `${url.pathname}${url.search}${url.hash}`);
  } catch {
    /* the token just stays in the address bar */
  }
}

function readStoredTab(): Tab {
  try {
    const stored = localStorage.getItem(TAB_STORAGE_KEY);
    if (TABS.some((t) => t.id === stored)) return stored as Tab;
  } catch {
    /* storage unavailable */
  }
  return "dashboard";
}

function App() {
  const [tab, setTab] = useState<Tab>(readStoredTab);
  const [theme, setTheme] = useTheme();
  const { account, refresh, signOut } = useAccount();
  const [signInToken, setSignInToken] = useState<string | null>(readSignInToken);

  // Switching account changes whose lists the pages should be showing, so they
  // are remounted rather than left holding the previous owner's data.
  const identity = account.signed_in ? (account.email ?? "account") : "anonymous";

  const handleTokenHandled = useCallback(() => {
    setSignInToken(null);
    clearSignInToken();
  }, []);

  // Reopening on the tab you left is worth more than always landing on the
  // dashboard, especially while the Fed tracker is being checked repeatedly.
  useEffect(() => {
    try {
      localStorage.setItem(TAB_STORAGE_KEY, tab);
    } catch {
      /* preference just won't persist */
    }
  }, [tab]);

  return (
    <div className="app">
      <a className="skip-link" href="#main-content">Skip to content</a>
      <header className="app-header">
        <div className="brand">
          <img src="/favicon.svg" alt="" className="brand-mark" />
          <div><h1>Vantage</h1><span className="brand-caption">A clearer view.</span></div>
        </div>

        <div className="header-actions">
          <nav aria-label="Main navigation">
            {TABS.map((t) => (
              <button
                key={t.id}
                className={tab === t.id ? "active" : ""}
                onClick={() => setTab(t.id)}
                aria-current={tab === t.id ? "page" : undefined}
              >
                {t.label}
              </button>
            ))}
          </nav>

          <AccountMenu
            account={account}
            onSignedIn={refresh}
            onSignOut={signOut}
            pendingToken={signInToken}
            onTokenHandled={handleTokenHandled}
          />

          <ThemePicker theme={theme} onChange={setTheme} />
        </div>
      </header>

      <AccountProvider value={account}>
        {/* Keyed by tab as well as identity so switching tabs clears a crash
            rather than stranding the reader on the error screen. */}
        <main id="main-content" tabIndex={-1} key={identity}>
          <ErrorBoundary key={tab}>
            {tab === "dashboard" && <DashboardPage />}
            {tab === "comparison" && <ComparisonPage />}
            {tab === "journal" && <JournalPage />}
            {tab === "fed" && <FedTrackerPage />}
          </ErrorBoundary>
        </main>
      </AccountProvider>

      <footer className="app-footer">
        <p>
          Vantage is a personal research tool. Data from Financial Modeling Prep; Fed
          summaries generated by Claude. Nothing here is investment advice.
        </p>
        <p className="footer-note">
          {account.signed_in
            ? `Saved to ${account.email}, so your watchlist follows you to any device.`
            : "Your watchlist is stored against this browser. Sign in to keep it on every device, or use Backup on the dashboard to save a copy."}
        </p>
      </footer>
    </div>
  );
}

export default App;
